let current = localStorage.getItem('pokyplane_lang') || 'en';

export function getLang() {
  return current;
}

export function t(key) {
  return dict[current]?.[key] ?? dict.en[key] ?? key;
}

export function setLang(lang) {
  if (!dict[lang]) return;
  current = lang;
  localStorage.setItem('pokyplane_lang', lang);
  applyDomLang();
}

export function applyDomLang() {
  const root = document.documentElement;
  root.lang = current;
  root.dir = current === 'fa' ? 'rtl' : 'ltr';
  root.classList.toggle('lang-fa', current === 'fa');
  root.classList.toggle('lang-en', current === 'en');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.placeholder !== undefined && el.hasAttribute('data-i18n-placeholder')) {
        el.placeholder = val;
      }
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
}
